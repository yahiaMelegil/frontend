export function getAdminDirection(language) {
  return language === 'ar' ? 'rtl' : 'ltr';
}

export function translateAdmin(language, key, replacements = {}) {
  const selectedLanguage = translations[language] ? language : ADMIN_DEFAULT_LANGUAGE;
  const value = translations[selectedLanguage][key] ?? translations[ADMIN_DEFAULT_LANGUAGE][key] ?? key;

  return Object.entries(replacements).reduce(
    (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
    value,
  );
}
