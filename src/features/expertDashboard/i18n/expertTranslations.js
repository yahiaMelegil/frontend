export function getExpertDirection(language) {
  return language === 'ar' ? 'rtl' : 'ltr';
}

export function translateExpert(language, key, replacements = {}) {
  const selectedLanguage = translations[language] ? language : EXPERT_DEFAULT_LANGUAGE;
  const value = translations[selectedLanguage][key] ?? translations[EXPERT_DEFAULT_LANGUAGE][key] ?? key;

  return Object.entries(replacements).reduce(
    (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
    value,
  );
}
